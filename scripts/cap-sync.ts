/**
 * `pnpm cap:sync` — writes the site URL the bundled offline page retries
 * (native/www/app-url.js) and runs `cap sync` for iOS and Android.
 *
 *   pnpm cap:sync                                   production (https://discontrol.app)
 *   CAP_SERVER_URL=http://192.168.1.71:3000 pnpm cap:sync   phone on the same Wi-Fi
 *
 * Only http(s) origins are accepted: the value ends up in a script tag.
 */
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { join } from "node:path";

const raw = process.env.CAP_SERVER_URL ?? "https://discontrol.app";
let origin: string;
try {
  const url = new URL(raw);
  if (url.protocol !== "https:" && url.protocol !== "http:") throw new Error("protocol");
  origin = url.origin;
} catch {
  console.error(`CAP_SERVER_URL is not an http(s) URL: ${raw}`);
  process.exit(1);
}
if (origin.startsWith("http:")) {
  console.warn(`[cap:sync] ${origin} is cleartext: development builds only, never upload this to a store.`);
}

writeFileSync(
  join(process.cwd(), "native/www/app-url.js"),
  `// Generated by scripts/cap-sync.ts. Do not edit.\nwindow.DISCONTROL_URL = ${JSON.stringify(origin)};\n`,
);
execFileSync("pnpm", ["exec", "cap", "sync", ...process.argv.slice(2)], { stdio: "inherit", env: { ...process.env, CAP_SERVER_URL: origin } });
